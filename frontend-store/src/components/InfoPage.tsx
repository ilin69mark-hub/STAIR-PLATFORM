import { useState } from 'react'
import { hasConsent, revokeConsent } from '@shared/consent'
import { CONTACTS } from '../config'

export type InfoPageKind = 'offer' | 'privacy' | 'cookies'

interface Props {
  kind: InfoPageKind
  onBack: () => void
}

const titles: Record<InfoPageKind, string> = {
  offer: 'Публичная оферта',
  privacy: 'Политика конфиденциальности',
  cookies: 'Политика использования cookie',
}

