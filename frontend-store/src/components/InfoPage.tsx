function Cookies() {
  const [granted, setGranted] = useState<boolean>(() => hasConsent())
  return (
    <div>
      <p>
        Настоящая политика объясняет, какие файлы cookie используются на Сайте, какие
        данные собираются и как управлять ими.
      </p>
      <h3>1. Что такое cookie</h3>
      <p>
        Cookie — небольшие текстовые файлы, которые сохраняются в вашем браузере и
        позволяют сайту запоминать ваши действия и предпочтения.
      </p>
      <h3>2. Какие cookie мы используем</h3>
      <p>
        Технически необходимые — они обеспечивают работу сайта: служебная cookie
        защиты от подделки запроса (CSRF). Без неё формы не отправляются, поэтому
        эти cookie не требуют отдельного согласия и не отключаются.
      </p>
      <h3>3. Какие данные собираются и зачем</h3>
      <p>
        Если вы разрешили сбор статистики, мы записываем: какие экраны вы открыли,
        какие шаги конструктора прошли, какие поля оставили пустыми, где расчёт не
        прошёл и на каком шаге вы ушли со страницы. Это нужно, чтобы понимать, где
        посетитель спотыкается, и улучшать конструктор.
      </p>
      <p>
        Чего мы НЕ собираем сами: содержимое заполненных полей, имена, адреса и
        телефоны. IP-адрес для подсчёта уникальных посетителей используется
        только как необратимый хеш (HMAC с серверной солью); без соли он не
        используется вовсе.
      </p>
      <h3>3.1. Яндекс.Метрика</h3>
      <p>
        Если владелец сайта вписал счётчик в настройках магазина, данные о
        посещении дополнительно обрабатываются сервисом Яндекс.Метрика: он
        узнаёт источник перехода, страну и устройство. Этот сервис выставляет
        свои cookie, поэтому подключается только после вашего согласия.
      </p>
      <p>
        Вебвизор (запись всех действий на странице) выключен и не включается.
        Поэтому содержимое полей ввода — включая имя, почту и телефон в форме
        заявки — в Метрику не передаётся.
      </p>
      <h3>4. Как отозвать согласие</h3>
      <p>
        Согласие можно отозвать в любой момент — сбор прекратится сразу.
      </p>
      <p>
        {granted ? (
          <>
            <span className="muted">Согласие сейчас действует. </span>
            <button
              className="sp-btn"
              onClick={() => {
                revokeConsent()
                setGranted(false)
              }}
            >
              Отозвать согласие
            </button>
          </>
        ) : (
          <span className="muted">Согласия нет — статистика не собирается.</span>
        )}
      </p>
      <h3>5. Управление cookie</h3>
      <p>
        Вы можете отключить cookie в настройках браузера. Отключение технически
        необходимых cookie повлияет на работу Сайта.
      </p>
    </div>
  )
}

// Инфо-страница: оферта, политика конфиденциальности или политика cookie.
export function InfoPage({ kind, onBack }: Props) {
  return (
    <div className="panel">
      <div className="info-head">
        <button className="btn btn--ghost" onClick={onBack}>
          ← Назад
        </button>
        <h1>{titles[kind]}</h1>
      </div>
      <div className="legal-text">
        {kind === 'offer' && <Offer />}
        {kind === 'privacy' && <Privacy />}
        {kind === 'cookies' && <Cookies />}
      </div>
    </div>
  )
}