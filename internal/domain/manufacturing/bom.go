package manufacturing

import (
	"stairplatform/internal/domain/engineering"
)

// Quantity — положительное целое количество деталей (BC-007).
type Quantity int

// BOMLine — строка спецификации: группа геометрически одинаковых деталей
// (одинаковый тип, материал и габариты). PartNumber — первая деталь группы,
// трассируемая к Parts.
type BOMLine struct {
	Number       int
	PartNumber   PartNumber
	Description  string
	MaterialCode MaterialCode
	Thickness    engineering.Length
	Quantity     Quantity
	Length       engineering.Length
	Width        engineering.Length
	// Numbers — стикеры всех экземпляров строки: в том же порядке, в каком
	// детали пришли из разложения.
	//
	// Раньше строка знала только первый номер (PartNumber) и количество, и
	// узнать, какие именно наклейки входят в позицию, было не по чему.
	// Спецификация при этом должна отвечать «какой стикер куда», а без
	// полного перечня она отвечает только «сколько и какого размера».
	Numbers []PartNumber
}

// BOM — спецификация изделия (MFG-0001). Порядок строк детерминирован.
type BOM struct {
	Lines []BOMLine
}

// CutItem — позиция карты раскроя: прямоугольник листового материала
// (длина × ширина × толщина) в количестве Quantity.
type CutItem struct {
	PartNumber   PartNumber
	MaterialCode MaterialCode
	Thickness    engineering.Length
	Length       engineering.Length
	Width        engineering.Length
	Quantity     Quantity

	// Profile — ТОЧНЫЙ плоский контур детали (S-163): многоугольник, который
	// вырезается из листа. Length×Width остаются описывающим прямоугольником
	// и по ним считается УКЛАДКА: для раскроя металла по габариту этого
	// достаточно. Profile нужен документу раскроя, чтобы он совпадал с
	// чертежом.
	//
	// Пустой контур означает «описать прямоугольником».
	Profile []Point2D

	// Holes — контуры отверстий детали в тех же координатах, что и Profile.
	//
	// Отверстия идут в документ реза вместе с контуром: лазер ведёт луч по
	// внешнему контуру и по каждому отверстию внутри. Без них оператор режет
	// контур и потом сверлит отверстия на глаз.
	//
	// Пустой срез означает «отверстий нет». Отверстия вне Profile сюда не
	// попадают: это технологические поля и вырезы под рельсы в заготовке,
	// лазер их не ведёт.
	Holes [][]Point2D

	// Сварной стык «шип-паз», которым кусок стыкуется с соседним. Деталь,
	// длиннее рабочего поля лазерного стола, режется на куски, и на карте
	// раскроя видно, где именно сваривать.
	HasTongue  bool // вырезать шип на торце
	HasMortise bool // вырезать сквозной паз
	// JointOnWidth — стык идёт поперёк детали (половинки оболочки колонны),
	// иначе — вдоль.
	JointOnWidth bool
	JointIndex   int // номер стыка, 0-based
	JointCount   int // стыков на детали, 0 — деталь цельная
}

// CutList — карта раскроя (MFG-0001): прямоугольники, вырезаемые из
// листового материала.
type CutList struct {
	Items []CutItem
}
