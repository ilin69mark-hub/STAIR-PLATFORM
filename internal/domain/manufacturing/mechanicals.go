package manufacturing

import (
	"fmt"
	"math"
)

// mechanicals.go — прочностные характеристики материала (S-237).
//
// Отдельно от производственных полей (Density, MinThickness, сортаж
// листа): одно — «что можно изготовить», другое — «что выдержит
// нагрузка». Смешивать их опасно: сейчас плотность есть, а
// прочности нет, и выглядит это как «материал посчитан».
//
// ЧТО ВАЖНО: характеристик может НЕ БЫТЬ. Тогда это StatusUnknown и
// расчёт прочности не выполняется вовсе, а не подставляется ноль и не
// выдаётся за подтверждённое значение (п. 74–76 библии нормативов,
// требование промта по Glass Railing: «если параметр неизвестен, он
// должен оставаться неизвестным»).
//
// Числа заполняются ТОЛЬКО из текста нормы с указанием источника и
// редакции. Пока текстов сверки нет — характеристики пустые; наполнение
// вынесено в отдельную карточку, потому что выдуманное сопротивление
// опаснее отсутствующего.

// MechanicalStatus — достоверность характеристик (S-237).
type MechanicalStatus string

const (
	// MechUnknown — характеристик нет. Расчёт прочности по материалу
	// НЕ выполняется, и это честно показывается в статусе и отчёте.
	MechUnknown MechanicalStatus = "unknown"
	// MechPartial — часть полей есть, часть нет. Расчёт по неполным
	// данным запрещён: считать от половины хуже, чем не считать.
	MechPartial MechanicalStatus = "partial"
	// MechKnown — значения есть, источник назван, расчёт можно вести.
	MechKnown MechanicalStatus = "known"
)

// Mechanicals — прочностные характеристики материала.
//
// Единый набор для стали, дерева и стекла: у материалов разные
// свойства, но инженеру нужен один контракт, а конкретные поля,
// которые осмысленны для его класса, заполняются, а остальные
// остаются нулевыми. Ноль означает «неизвестно», а не «ноль прочности»:
// это различает Status.
type Mechanicals struct {
	// YieldMPa — предел текучести (сталь) или предел прочности при
	// изгибе для древесины (СП 64), МПа.
	YieldMPa float64
	// TensileMPa — предел прочности на растяжение, МПа (сталь, стекло).
	TensileMPa float64
	// ElasticModulusMPa — модуль упругости E, МПа.
	ElasticModulusMPa float64
	// CompressiveMPa — предел прочности на сжатие, МПа (бетон, дерево).
	CompressiveMPa float64
	// BearingPerpMPa — расчётное сопротивление СМЯТИЮ ПОПЕРЁК волокон
	// (СП 64 табл. 3 поз. 4а, опорные части конструкций), МПа.
	//
	// Отдельное поле не для полноты, а ради безопасности: у древесины
	// сопротивление поперёк волокон в несколько раз ниже продольного.
	// Ступень лежит на косоуре и нагружает его именно поперёк, поэтому
	// проверка опорной зоны по CompressiveMPa завысила бы несущую
	// способность в разы. Ноль = неизвестно (у стали такого НДС нет).
	BearingPerpMPa float64
	// ShearAlongMPa — расчётное сопротивление СКАЛЫВАНИЮ ВДОЛЬ волокон
	// (СП 64 табл. 3 поз. 5а, цельная древесина при изгибе), МПа.
	//
	// Управляет проверкой несущей способности опорных узлов у вырезов и
	// врезок. Ноль = неизвестно.
	ShearAlongMPa float64
	// SafetyFactor — коэффициент надёжности по материалу γm (СП 16 табл. 3).
	//
	// Хранится НОРМАТИВНОЕ сопротивление, а не расчётное: Ryn/Run, а не
	// Ry/Ru. Расчётное получается делением на γm по п. 6.1 СП 16, и
	// хранить оба вида сразу опасно — умножение на γm поверх уже
	// поделённого сопротивления даёт двойной запас в обратную сторону.
	SafetyFactor float64
	// SafetyFactorEmbedded — γm НЕ применяется: норма уже заложила его в
	// значения (СП 64.13330, табл. 3 для древесины по сортам, где R_A —
	// расчётное сопротивление влажностью 12%, уже уменьшенное на коэффициент
	// длительности прочности).
	//
	// Отдельный флаг, а не «SafetyFactor = 1»: единица выглядит как
	// подтверждённая величина и прошла бы в расчёт как настоящий коэффициент,
	// тогда как на самом деле методика другая. Без флага древесина навсегда
	// осталась бы в статусе partial.
	SafetyFactorEmbedded bool
	// Source — документ, пункт и редакция, откуда взяты значения.
	// Без него характеристики не считаются подтверждёнными: тот же
	// принцип, что в правилах нормативов (S-235).
	Source string
}

// HasSafetyFactor — известен ли коэффициент надёжности явно или он уже
// сидит внутри значений. Ноль без флага — это «неизвестно», и такой набор
// нельзя считать пригодным для расчёта.
func (m *Mechanicals) HasSafetyFactor() bool {
	return m != nil && (m.SafetyFactor > 0 || m.SafetyFactorEmbedded)
}

// Status — достоверность набора.
//
// Правило: если Source не назван — набор НЕ известен, даже если числа
// заполнены (числа без источника выглядят как подтверждённые и опасны
// именно этим). Если названы, но заполнены не все поля, которые нужны
// для расчёта, — Partial: какие именно нужны, решает расчётный модуль,
// поэтому здесь считаем неполным любой набор без Source и любой с
// пропуском базовых полей.
func (m *Mechanicals) Status() MechanicalStatus {
	if m == nil {
		return MechUnknown
	}
	if m.Source == "" {
		return MechUnknown
	}
	if m.ElasticModulusMPa <= 0 || !m.HasSafetyFactor() ||
		(m.YieldMPa <= 0 && m.TensileMPa <= 0 && m.CompressiveMPa <= 0) {
		return MechPartial
	}
	return MechKnown
}

// Known — можно ли вести расчёт прочности по этому набору. Проверка в
// один вызов, чтобы код расчёта не решал, что считать достаточным.
func (m *Mechanicals) Known() bool { return m.Status() == MechKnown }

// Validate — самосогласованность набора. Ошибка о несоответствии
// себе, а не «нет данных»: отсутствие — это StatusUnknown, и оно
// допустимо (материал нужен и для производства без прочностей).
func (m *Mechanicals) Validate(code string) error {
	if m == nil {
		return nil
	}
	for name, v := range map[string]float64{
		"yield": m.YieldMPa, "tensile": m.TensileMPa,
		"modulus": m.ElasticModulusMPa, "compressive": m.CompressiveMPa,
		"bearing perpendicular": m.BearingPerpMPa, "shear along": m.ShearAlongMPa,
		"safety factor": m.SafetyFactor,
	} {
		if math.IsNaN(v) || math.IsInf(v, 0) || v < 0 {
			return fmt.Errorf("manufacturing: material %q mechanical %s is invalid: %v",
				code, name, v)
		}
	}
	if m.Source != "" && m.Known() {
		if m.SafetyFactor > 0 && m.SafetyFactor < 1 {
			return fmt.Errorf("manufacturing: material %q safety factor %v must be >= 1",
				code, m.SafetyFactor)
		}
	}
	return nil
}
