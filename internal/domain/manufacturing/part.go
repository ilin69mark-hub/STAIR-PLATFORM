package manufacturing

import (
	"stairplatform/internal/domain/engineering"
)

// PartKind — тип производственной детали, выведенный из геометрии
// (декомпозиция, MFG-0002).
type PartKind string

const (
	// PartStringer — косоур: тело, тонкое по ширине марша (ось Y).
	PartStringer PartKind = "stringer"
	// PartTread — проступь: тело, тонкое по вертикали (ось Z).
	PartTread PartKind = "tread"
	// PartRiser — подступенок: тело, тонкое по глубине (ось X).
	PartRiser PartKind = "riser"
	// Пятки обоймы выреза металлокаркаса (решение владельца 2026-10-05) —
	// плоские детали из листа 4 мм с отверстиями и регулировочными овалами:
	// PartHeel — пятка 1 под ступенью, PartWeb — пятка 2 вдоль зуба,
	// PartAnchor — крепление косоура к полу и к перекрытию второго этажа,
	// PartFirstWeb — пластина 1-й ступени между косоурами.
	PartHeel     PartKind = "heel"
	PartWeb      PartKind = "web"
	PartAnchor   PartKind = "anchor"
	PartFirstWeb PartKind = "first_web"
)

// IsValid проверяет корректность типа детали.
func (k PartKind) IsValid() bool {
	switch k {
	case PartStringer, PartTread, PartRiser,
		PartHeel, PartWeb, PartAnchor, PartFirstWeb:
		return true
	}
	return false
}

// PartNumber — уникальный номер производственной детали (BC-007).
type PartNumber string

// Part — производственная деталь, декомпозированная из твёрдого тела
// модели. SolidIndex трассирует деталь к геометрии (BC-007: все позиции
// BOM трассируются до геометрии). Length ≥ Width — габариты детали в
// плоскости, Thickness — тонкий размер.
type Part struct {
	Number     PartNumber
	Kind       PartKind
	Material   MaterialCode
	Thickness  engineering.Length // мм — тонкий размер
	Length     engineering.Length // мм — наибольший габарит в плоскости
	Width      engineering.Length // мм — наименьший габарит в плоскости
	SolidIndex int                // трассировка к твёрдому телу модели
	// CutPerimeterMM — длина лазерного реза детали: периметр КОНТУРА плюс
	// периметры всех отверстий и регулировочных овалов внутри (MMF-0006).
	// Считается из геометрии тела, а не из габарита: деталь 270×50 с шестью
	// отверстиями режется дольше такой же пластинки без отверстий, и разница
	// это и есть работа.
	CutPerimeterMM float64
	// MillEdgeLengthMM — длина кромки, которую на детали фрезеруют (0 = фрезеровка
	// не нужна). Заполняется из GenerationResult.MillingFeatures, то есть из
	// геометрии: длина ребра — не характеристика заготовки, а объём работы.
	//
	// Заготовка при этом остаётся прямоугольной: скругление носа снимается
	// сверху, поэтому раскрой и закупка листа не меняются, меняется только
	// техмаршрут и время.
	MillEdgeLengthMM float64
	// MillRadiusMM — радиус скругления, мм. В тариф не входит, но хранится
	// рядом с длиной: по детали должно быть видно, ЧТО именно фрезеровали.
	MillRadiusMM float64
	// JointIndex — порядковый номер куска детали, если деталь резалась на
	// несколько (0 — деталь цельная). По нему видно порядок сборки: куски
	// ставятся подряд, и стык идёт между соседними.
	JointIndex int
	// JointCount — сколько всего кусков у детали (1 — цельная).
	JointCount int
	// HasTongue / HasMortise — признаки сварного стыка «шип-паз» (шпатка
	// технолога 2026-10-05): в одном куске на торце выпиливается паз, в
	// следующем на торце есть шип. Оба признака нужны рисунку раскроя:
	// без них куски выглядят одинаковыми, и монтажник не видит, какой
	// кусок к какому примыкает.
	HasTongue  bool
	HasMortise bool
	// JointOnWidth — стык идёт поперёк детали, а не вдоль. Так режется
	// широкая развёртка обечайки: её ширина 2πr шире поля стола, и деталь
	// делится на половинки оболочки. У косоура поперечный рез недопустим —
	// он отделил бы зубья гребёнки от спинки.
	JointOnWidth bool
	// HoleCount — число отверстий в детали (MNT-0001). Заполняется из
	// геометрии тела: отверстия в пятках обоймы выреза режет лазер вместе
	// с контуром, и по одному отверстию на каждый комплект крепежа.
	//
	// Раньше поле не существовало, и крепёж в смете не считался: пятки
	// просверливались, а стоимость дюбелей и глухарей в расчёте была нулём.
	HoleCount int
}

// IsJointPiece — кусок детали со сварным стыком (то есть деталь резалась).
func (p Part) IsJointPiece() bool { return p.JointCount > 1 }

// NeedsMilling сообщает, требует ли деталь фрезеровной операции.
func (p Part) NeedsMilling() bool { return p.MillEdgeLengthMM > 0 }
