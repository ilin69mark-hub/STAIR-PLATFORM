package manufacturing

// Vec3 — направление или точка в системе координат изделия, мм.
//
// Отдельный тип от геометрического ядра: домен не зависит от движка (иначе
// расчёт стоимости зависел бы от построения геометрии), а копировать три
// float64 ради одного поля — значит размножить то, что и так приходит из
// одного места.
type Vec3 struct {
	X, Y, Z float64
}

// Placement — положение детали в сборке.
//
// Чего не было и что теперь есть. Деталь существовала только как заготовка
// (Length/Width/Thickness) и как ссылка на тело модели по индексу
// (SolidIndex). «Куда она ставится» не знал никто, поэтому:
//
//   - сборочный чертёж с номерами деталей нарисовать было нечем;
//   - строка спецификации «стикер FLG-111 → куда» не на что было опереться;
//   - при переносе на FreeCAD-библиотеку (Фаза 1) калькулятору нужно было бы
//     знать, КУДА поставить присланную деталь.
//
// Система координат та же, что у профиля детали: начало в минимальной точке
// контура, X вдоль длинного ребра. Placement переводит её в мировую:
//
//	мир = Origin + u·U + v·V
//
// Placement и Profile заполняются из ОДНОЙ рамки (ProfileFrame в движке
// геометрии), поэтому контур на раскрое и деталь на сборке не могут разойтись
// в разные стороны: разойтись им просто не из чего.
type Placement struct {
	// Origin — точка, которой соответствует начало профиля (0, 0).
	Origin Vec3
	// U, V — единичные векторы вдоль осей профиля X и Y.
	U, V Vec3
	// N — единичная нормаль к плоскости детали (тонкая ось).
	N Vec3
	// Known — положение вычислено. false у деталей, у которых тонкой оси
	// нет (составные и вырожденные тела), и у ПОКУПНЫХ деталей ограждения:
	// они не приходят из тел модели, потому что тела ограждения строятся
	// как декор и в Model не входят (appendRailingMesh).
	//
	// Поле, а не нули вместо положения: нули — это тоже точка, и деталь,
	// нарисованная в начале координат, выглядит как ошибка раскроя. Честное
	// «не знаю» позволяет документу не рисовать лишнего.
	Known bool
}

// WorldAt — мировая точка по координатам профиля детали.
func (p Placement) WorldAt(u, v float64) Vec3 {
	return Vec3{
		X: p.Origin.X + u*p.U.X + v*p.V.X,
		Y: p.Origin.Y + u*p.U.Y + v*p.V.Y,
		Z: p.Origin.Z + u*p.U.Z + v*p.V.Z,
	}
}

// Center — мировая точка центра детали при заданных габаритах заготовки.
func (p Placement) Center(length, width float64) Vec3 {
	return p.WorldAt(length/2, width/2)
}
