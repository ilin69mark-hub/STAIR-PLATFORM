package geometry

import "math"

// Circle2D — окружность в системе координат профиля детали.
type Circle2D struct {
	Center Point2D
	Radius float64
}

// CircleFitToleranceMM — насколько многоугольник может уходить внутрь
// окружности, и это отверстие всё равно записывается в DXF как CIRCLE.
//
// Число взято от действующих допусков проекта, а не выбрано само по себе:
//
//   - DefaultArcToleranceMM = 0,05 мм — допуск дуги по умолчанию;
//   - combArcToleranceMM = 0,055 мм — допуск обоймы выреза (пятки режутся).
//
// Отверстия пяток Ø10 и Ø12 укладываются в 0,0428 и 0,0513 мм, то есть
// проходят. Порог 0,06 мм берётся с запасом выше обоих.
//
// Что означает «проходит». Многоугольник из N точек на окружности радиуса R
// уходит внутрь её на величину прогиба (sagitta) R·(1 − cos(π/N)). Пока этот
// прогиб в пределах допуска, многоугольник — верное приближение окружности,
// и подмена его на CIRCLE двигает границу отверстия не дальше, чем на
// собственную погрешность построения.
//
// Это УЛУЧШЕНИЕ, а не допущение: физическое отверстие просверлено или
// прорезано по окружности, а многоугольник — это её приближение для
// тесселяции. Записав CIRCLE, мы возвращаем детали её настоящую форму.
const CircleFitToleranceMM = 0.06

// Допуск подгонки окружности ПО ТОЧКАМ. Отдельно от CircleFitToleranceMM,
// потому что это две разные вещи:
//
//   - подгонка по точкам — «насколько вершины лежат на одной окружности»;
//     это вопрос определённости, и здесь нужен предел порядка
//     машинного нуля;
//   - прогиб многоугольника — «насколько рёбра уходят внутрь»; это вопрос
//     верности приближения, и здесь нужен производственный допуск.
const circleFitPrecisionMM = 1e-6

// CircleFromPoints — окружность, описанная точками замкнутого контура, если
// этот многоугольник — верное приближение окружности.
//
// Два условия, оба обязательные:
//
//  1. Все вершины лежат на одной окружности (точность circleFitPrecisionMM).
//     Иначе контур круглый только местами, и подменять его окружностью нельзя:
//     сплющивание заметят на чертеже.
//  2. Прогиб рёбер многоугольника внутрь окружности не превышает
//     CircleFitToleranceMM. Иначе многоугольник — грубое приближение, и
//     CIRCLE изменил бы деталь сильнее, чем погрешность её построения.
//
// Второе условие — то, что делает подмену честной. Без него распознавание
// сводилось бы к «точки лежат на окружности», а многоугольник из трёх точек
// проходит его тривиально и при этом отличается от окружности на половину
// радиуса.
//
// Требование трёх точек — минимальное для определения окружности через три
// точки. Контуры короче окружностью быть не могут.
func CircleFromPoints(pts []Point2D) (Circle2D, bool) {
	if len(pts) < 3 {
		return Circle2D{}, false
	}
	c, ok := circleThrough(pts[0], pts[1], pts[2])
	if !ok {
		return Circle2D{}, false
	}
	if c.Radius <= circleFitPrecisionMM {
		// Вырожденная окружность: нулевой радиус — это точка, а не отверстие,
		// и CIRCLE с R = 0 часть CAM-систем не принимает.
		return Circle2D{}, false
	}
	for _, p := range pts {
		if math.Abs(math.Hypot(p.X-c.Center.X, p.Y-c.Center.Y)-c.Radius) > circleFitPrecisionMM {
			return Circle2D{}, false
		}
	}
	if c.chordDeviationMM(pts) > CircleFitToleranceMM {
		return Circle2D{}, false
	}
	return c, true
}

// chordDeviationMM — прогиб многоугольника внутрь описанной окружности.
//
// Берётся по серединам рёбер: середина хорды ближе всего к центру, и
// расстояние от центра до середины ребра равно R − прогиб. Минимум по всем
// рёбрам — самый глубокий прогиб контура.
func (c Circle2D) chordDeviationMM(pts []Point2D) float64 {
	best := math.Inf(1)
	for i := range pts {
		j := (i + 1) % len(pts)
		mx := (pts[i].X + pts[j].X) / 2
		my := (pts[i].Y + pts[j].Y) / 2
		d := math.Hypot(mx-c.Center.X, my-c.Center.Y)
		if d < best {
			best = d
		}
	}
	return c.Radius - best
}

// circleThrough — окружность через три точки. Второе значение — «точки не
// лежат на одной окружности» (совпадающие точки или коллинеарные).
//
// Формула: центр — пересечение серединных перпендикуляров двух хорд, радиус —
// расстояние от центра до любой точки.
func circleThrough(a, b, c Point2D) (Circle2D, bool) {
	// Удвоенные площади: знаменатель формулы. Ноль — точки коллинеарны или
	// совпадают, окружности через них нет (была бы бесконечная прямая).
	d := 2 * (a.X*(b.Y-c.Y) + b.X*(c.Y-a.Y) + c.X*(a.Y-b.Y))
	if math.Abs(d) <= circleFitPrecisionMM {
		return Circle2D{}, false
	}
	a2 := a.X*a.X + a.Y*a.Y
	b2 := b.X*b.X + b.Y*b.Y
	c2 := c.X*c.X + c.Y*c.Y
	ux := (a2*(b.Y-c.Y) + b2*(c.Y-a.Y) + c2*(a.Y-b.Y)) / d
	uy := (a2*(c.X-b.X) + b2*(a.X-c.X) + c2*(b.X-a.X)) / d
	return Circle2D{
		Center: Point2D{X: ux, Y: uy},
		Radius: math.Hypot(a.X-ux, a.Y-uy),
	}, true
}
