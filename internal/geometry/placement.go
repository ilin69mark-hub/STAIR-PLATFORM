package geometry

// Placement — положение плоской детали в системе координат изделия.
//
// Зачем он. Деталь до сих пор существовала в двух независимых видах: как
// габарит заготовки в раскрое (Part.Length/Width/Thickness + Profile) и как
// тело в модели (Solid). Связывать их приходилось по индексу (SolidIndex),
// и «куда ставить» не знал никто: у детали не было ни положения, ни
// ориентации.
//
// Без положения невозможны три вещи, которые владельцу нужны прямо сейчас:
//
//   - сборочный чертёж с номерами деталей;
//   - строка спецификации «стикер FLG-111 → фланец, опора 2, левый край»;
//   - выносная операция на производстве: «сварить деталь, поставленную вот
//     сюда».
//
// Система координат ПЛОСКИХ деталей. Профиль детали (SolidProfile2D) живёт
// в своей двумерной системе: начало в минимальной точке контура, X вдоль
// самого длинного ребра. Placement переводит эту систему в мировую:
//
//	мир = Origin + u·U + v·V
//
// где u, v — координаты точки в профиле. Три значения согласованы по
// построению: они берутся из той же ProfileFrame, что и сам профиль, поэтому
// контур на раскрое и деталь на сборке не могут разойтись.
type Placement struct {
	// Origin — мировая точка, которой соответствует начало профиля (0, 0).
	Origin Point3
	// U — единичный мировой вектор вдоль оси профиля X (длинное ребро).
	U Vector3
	// V — единичный мировой вектор вдоль оси профиля Y.
	V Vector3
	// N — единичная нормаль к плоскости детали, вдоль тонкой оси.
	//
	// Знак фиксирован осью тонкой стороны тела, а не «наружу от изделия»:
	// переворачивать нормаль значило бы сделать её зависимой от того, с какой
	// стороны смотрят, и положение перестало бы быть воспроизводимым.
	N Vector3
}

// SolidPlacement — положение плоского тела в сборке.
//
// Второе значение — «положение вычислено». У составных и вырожденных тел
// тонкой оси нет, рамка не строится, и вызывающий обязан оставить деталь без
// положения: лучше честно «не знаю», чем поставить деталь в начало координат
// и нарисовать её не там.
func SolidPlacement(solid *Solid) (Placement, bool) {
	f, ok := NewProfileFrame(solid)
	if !ok {
		return Placement{}, false
	}
	return Placement{Origin: f.Origin, U: f.U, V: f.V, N: f.N}, true
}

// WorldAt — мировая точка по координатам профиля.
func (p Placement) WorldAt(u, v float64) Point3 {
	return Point3{
		X: p.Origin.X + u*p.U.X + v*p.V.X,
		Y: p.Origin.Y + u*p.U.Y + v*p.V.Y,
		Z: p.Origin.Z + u*p.U.Z + v*p.V.Z,
	}
}

// Center — мировая точка центра детали. Для прямоугольной заготовки это
// середина габарита профиля, то есть середина детали.
func (p Placement) Center(length, width float64) Point3 {
	return p.WorldAt(length/2, width/2)
}
