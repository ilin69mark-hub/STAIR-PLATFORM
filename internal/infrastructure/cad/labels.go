package cad

import (
	"encoding/csv"
	"fmt"
	"io"

	dommfg "stairplatform/internal/domain/manufacturing"
)

// СПИСОК НАКЛЕЕК (Фаза 0.4).
//
// Владелец решил: стикер — отдельная наклейка, а не протравка лазером.
// Поэтому на каждую деталь нужен печатный файл: что клеить и куда.
//
// Формата два, по решению владельца — на ВСЕ детали изделия:
//
//  1. CSV — машинная ведомость для печати наклеек на принтере этикеток.
//     Одна строка = одна наклейка = одна деталь: у каждой детали свой номер,
//     поэтому количества в строке нет.
//  2. Лист наклеек для просмотра и печати — рисуется во фронте (PDF через
//     jsPDF, который уже подключён) по тем же данным: номер, место, материал.
//
// Почему CSV делает сервер, а лист — фронт. CSV — это данные, и данные
// живут на сервере рядом с пакетом. Лист — это вёрстка, и вёрстка живёт
// там, где её печатают. Разделить их значит не дублировать источник:
// фронт читает тот же CSV, а не просит «то же, но красиво».

// LabelColumns — заголовок ведомости наклеек. Порядок зафиксирован: принтер
// этикеток настраивается один раз на колонки, и смена порядка сломает
// настроенные шаблоны печати.
var LabelColumns = []string{
	"номер", "куда", "деталь", "материал", "толщина_мм", "длина_мм", "ширина_мм",
}

// WriteLabels — ведомость наклеек в CSV.
//
// Строки идут в том же порядке, что и детали в пакете: порядок нумерации
// совпадает с порядком сборки, и наклейки печатаются в том порядке, в
// котором детали ставятся. Перемешивать их значило бы заставить монтажника
// искать.
//
// Покупные детали ограждения в ведомость входят: у них тоже есть номера,
// и наклейка им нужна. «Куда» у них нет — поле остаётся пустым, и это видно:
// пустое «куда» в строке означает «место не вычислено», а не «места нет».
func WriteLabels(w io.Writer, pkg *dommfg.ManufacturingPackage) error {
	if pkg == nil {
		return ErrNoPackage
	}
	out := csv.NewWriter(w)
	out.Comma = ';'
	if err := out.Write(LabelColumns); err != nil {
		return fmt.Errorf("cad: labels header: %w", err)
	}
	for _, p := range pkg.Parts {
		row := []string{
			string(p.Number),
			p.Where,
			string(p.Kind),
			string(p.Material),
			formatMM(p.Thickness.Millimeters()),
			formatMM(p.Length.Millimeters()),
			formatMM(p.Width.Millimeters()),
		}
		if err := out.Write(row); err != nil {
			return fmt.Errorf("cad: labels row %s: %w", p.Number, err)
		}
	}
	out.Flush()
	return out.Error()
}

// formatMM — миллиметры для ведомости. Одна цифра после запятой: принтер
// этикеток печатает текст, а не чертёж, и шесть цифр после запятой на
// наклейке — это шум, а не точность.
func formatMM(v float64) string {
	return fmt.Sprintf("%.1f", v)
}
