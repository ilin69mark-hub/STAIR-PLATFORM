package stair

import (
	"fmt"

	"stairplatform/internal/engine/validation"
)

// report.go — сборка развёрнутого отчёта проверки (S-240).
//
// Отчёт собирается в сервисном слое, а не в движке: только здесь известно,
// ЧТО ИМЕННО не посчитано. Движок видит геометрию и правила, но не знает,
// что расчётная схема площадки не построена, потому что её нет как
// сущности. Собирать отчёт в движке значило бы писать причины вслепую.

// Report — развёрнутый отчёт по трём уровням.
//
// Метод, а не поле: отчёт — производное от Validation и не должен
// разъезжаться с ним, если результат собрали в одном из ранних выходов
// конвейера, где эхо конфигурации ещё не заполнено.
func (r *Result) Report() *validation.Report {
	if r == nil {
		return nil
	}
	return validation.BuildReport(r.Validation, false, r.calcNotPerformedReasons())
}

// calcNotPerformedReasons — почему прочность не посчитано.
//
// Список НЕ пустой и НЕ общий: пустой список при статусе not_performed
// выглядит как забытый модуль, а перечисление даёт человеку понять, чего
// конкретно не хватает. Каждая причина ссылается на то, что известно:
// пласт карточек, конкретный стандарт и конкретный пробел в нём.
//
// Причины зависят от материалов заказа: несуглеродистая лестница и
// деревянная блокируются разным. Перечислять всё подряд было бы враньём
// в другую сторону — список длинный и часть пунктов к заказу отношения не
// имеет.
func (r *Result) calcNotPerformedReasons() []string {
	var reasons []string

	// Главная и общая для всех заказов: нет расчётной схемы площадки.
	reasons = append(reasons,
		"нет расчётной схемы несущей конструкции площадки: площадка существует "+
			"как висячая плита без рамы и опор (пласт S-226…S-234 отложен)")

	// Материал-зависимое.
	if r != nil && r.Material != "" {
		reasons = append(reasons, materialReason(r.Material, "каркаса")...)
	}
	if r != nil && r.TreadMaterial != "" && r.TreadMaterial != r.Material {
		reasons = append(reasons, materialReason(r.TreadMaterial, "ступеней")...)
	}

	// Соединения не проверяются ни для какого материала.
	reasons = append(reasons,
		"соединения не проверяются: болты, анкеры и сварные швы считаются "+
			"штуками, а не напряжениями; отверстия под расчёт не заведены")

	return reasons
}

// materialReason — что мешает посчитать прочность для конкретного
// материала. Пустой результат означает, что по этому материалу препятствий
// в известном нам перечне нет, и это НЕ значит «всё посчитано»: расчёт
// всё равно не выполняется по схеме площадки.
func materialReason(code, where string) []string {
	switch code {
	case "STAINLESS-304":
		return []string{
			fmt.Sprintf(
				"%s из нержавейки AISI 304: коэффициент надёжности по материалу "+
					"не определён — ГОСТ 11068-81 изделие-стандарт, он даёт свойства, "+
					"а не расчётные сопротивления, а аналога СП 16 для нержавеющей "+
					"стали в нормативной базе нет", where),
			fmt.Sprintf(
				"%s из нержавейки AISI 304: применение Ø42,4×1,5 — решение владельца "+
					"2026-10-14, диаметр вне сортамента ГОСТ 11068-81, сертификата "+
					"соответствия стандарту на изделие не будет", where),
		}
	case "WOOD-OAK", "WOOD-ASH":
		return []string{
			fmt.Sprintf(
				"%s из твёрдой лиственной породы: модуль упругости в СП 64.13330 "+
					"не приведён, расчёт по деформациям невозможен", where),
			fmt.Sprintf(
				"%s из твёрдой лиственной породы: п. 5.1 СП 64 разрешает такие породы "+
					"только для нагелей, подушек и «других деталей» — применение в "+
					"несущих элементах оформлено как отклонение владельца 2026-10-14", where),
		}
	case "WOOD-WALNUT":
		return []string{
			fmt.Sprintf(
				"%s из ореха: в СП 64.13330 порода не упомянута ни разу — ни "+
					"сопротивлений, ни переходных коэффициентов, ни плотности", where),
		}
	}
	return nil
}
