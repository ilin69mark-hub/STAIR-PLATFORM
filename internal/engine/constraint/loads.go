// loads.go — нормативные нагрузки (п. 77 библии нормативов).
//
// Это ПЕРВАЯ фактическая нормативная нагрузка проекта. До сих пор
// считать было нечего по существу: правила проверяли размеры, а чем
// нагружать конструкцию — не отвечал никто. Проверка прочности (п. 78)
// без нагрузки бессмысленна, и любой разговор о «несущей способности»
// без неё был бы фразой.
//
// Источник: СП 20.13330.2016 (приказ Минстроя № 891/пр от 03.12.2016,
// ред. от 14.12.2023, Изменение № 5). Значения сверены с официальным
// текстом, включая формулы: в HTML-выжимке мейнормы формулы вырезаются
// целиком, поэтому γf подтверждён по PDF-изданию.
//
// Приходят эти значения не из воздуха, а по цепочке: п. 5.2.2 ГОСТ
// 25772-2025 отправляет расчёт прочностных характеристик ограждений к
// нормативным документам по нагрузкам, и для ограждений лестничных
// маршей это СП 20.13330.2016 п. 8.2.6.
//
// ОБЛАСТЬ ПРИМЕНЕНИЯ (решение владельца 2026-10-14): пока проектируются
// только лестницы в ЖИЛЫХ зданиях. Это не «пока некогда», а осознанное
// сужение области, и оно меняет главное.
//
// При полном наборе назначений величины п. 8.2.6 б) 1,5 кН/м (трибуны и
// спортивные залы) и п. 8.2.6 г) 0,3 кН/м (обслуживающие площадки) НИ
// ОДНОМУ назначению не соответствуют, и лестница в спортивном сооружении
// молча получила бы 0,8 кН/м — недобор в два раза. В жилом scope этого
// класса зданий нет, и опасный пробел уходит вместе с ним.
//
// Обратная сторона, которую надо помнить: функции ниже по-прежнему
// отвечают для всех четырёх назначений, и профиль для public/industrial
// остаётся доступен. Если область расширят, значения 0,8 и 4,0 снова
// становятся неполными и ДОЛЖНЫ быть перепроверены до того, как заказ
// уйдёт в расчёт. Поэтому в RailingLoad.Note и StepLoad.Note названия
// неприменимых случаев остаются: это не бумажная оговорка, а список
// того, что надо снять при расширении области.

// RailingLoad — нормативная горизонтальная нагрузка на поручень.
//
// Нормативное (базовое) значение, а не расчётное: по п. 4.1 СП 20
// именно нормативное значение является основной характеристикой
// нагрузки, а расчётное получается умножением на коэффициент надёжности
// по нагрузке. Хранить нормативное и применять γf в расчётном модуле —
// правильнее, чем зашивать одно в другое: γf зависит от предельного
// состояния, а не от материала.
type RailingLoad struct {
	// NormativeKNPerM — нормативное значение, кН/м.
	NormativeKNPerM float64
	// Doc и Clause — откуда взято значение.
	Doc    string
	Clause string
	// Basis — дословный смысл пункта: какие здания охвачены.
	Basis string
	// GammaF — коэффициент надёжности по нагрузке γf. Ноль означает
	// «нормой не установлено», а НЕ единицу.
	//
	// Значение 1,2 взято из третьего абзаца п. 8.2.7 СП 20.13330.2016
	// («Для нагрузок, указанных в 8.2.6, следует принимать коэффициент
	// надёжности по нагрузке γf = 1,2»), введённого Изменением № 2.
	// Второй абзац того же пункта даёт 1,3/1,2 для равномерно
	// распределённых нагрузок — это ДРУГИЕ нагрузки, и путать их нельзя.
	GammaF float64
	// Note — оговорки: какие случаи дают другое значение и почему
	// выбранное применимо здесь.
	Note string
}

// Known — значение применимо. Ноль нагрузки невозможен физически, так
// что ноль здесь означает ровно одно: данных нет.
func (l RailingLoad) Known() bool { return l.NormativeKNPerM > 0 }

// DesignKNPerM — расчётное значение по п. 4.2 СП 20: нормативное,
// умноженное на коэффициент надёжности по нагрузке.
//
// Возвращает 0, если γf не подтверждён: считать по нормативному и
// назвать это расчётным — ровно та подмена, ради которой заведён
// Mechanicals.Status. Расчёт по прогибу (2-я группа предельных
// состояний) по п. 4.2 б) идёт при γf = 1, но это решение расчётного
// модуля, а не наше.
func (l RailingLoad) DesignKNPerM() float64 {
	if !l.Known() || l.GammaF <= 0 {
		return 0
	}
	return l.NormativeKNPerM * l.GammaF
}

const (
	loadDocSP20   = "СП 20.13330.2016 (ред. 14.12.2023)"
	loadClause826 = "п. 8.2.6"
	// gammaF12 — γf = 1,2 из п. 8.2.7 (абзац 3) для нагрузок п. 8.2.6
	// и из п. 8.3.5 для сосредоточенных нагрузок п. 8.3.4. Оба пункта
	// введены Изменением № 2 от 30.01.2019 и в последующих редакциях
	// не менялись.
	gammaF12 = 1.2
)

// RailingLoadFor — нормативная нагрузка на поручень по назначению
// здания.
//
// ВАЖНО, ЧТО ЗДЕСЬ НАШЕ, А ЧТО ИЗ НОРМЫ. Четыре значения в п. 8.2.6
// приведены для КЛАССОВ ЗДАНИЙ, которых в проекте нет: «жилые здания»,
// «трибуны и спортивные залы», «другие здания и помещения»,
// «обслуживающие площадки, мостики, ограждения крыш». Проект же оперирует
// назначением (house / flat / public / industrial, S-236). Соответствие
// между ними — РЕШЕНИЕ проекта, а не цитата из СП 20, и оно не
// единственно возможное. Поэтому оно сделано явным и оговорённым:
//
//   - house и flat отнесены к «жимым зданиям» (п. 8.2.6 а) — прямое
//     попадание, дом и многоквартирный дом оба жилые;
//   - public и industrial отнесены к «другим зданиям и помещениям»
//     (п. 8.2.6 в) — они не жилые и не трибуны;
//   - 1,5 кН/м (спортзалы и трибуны) НЕ назначено ни одному профилю:
//     лестница в спортзале получила бы 0,8 и недобор нагрузки вдвое;
//     этот случай требует отдельного назначения, которого пока нет;
//   - 0,3 кН/м (обслуживающие площадки) — тоже не назначено: обслуживающая
//     площадка не определяется назначением здания, а условием
//     эксплуатации.
//
// Обе невыданные величины записаны в Note, чтобы их нельзя было
// потерять: пока назначения нет, молча брать 0,8 — значит занизить
// нагрузку на лестнице в спортивном сооружении.
func RailingLoadFor(p engineering.BuildingPurpose) RailingLoad {
	switch p.PurposeEffective() {
	case engineering.PurposeHouse, engineering.PurposeFlat:
		return RailingLoad{
			NormativeKNPerM: 0.5,
			Doc:             loadDocSP20,
			Clause:          loadClause826 + " а)",
			Basis: "жилые здания, дошкольные организации, дома отдыха, " +
				"санатории, больницы и другие лечебные учреждения",
			GammaF: gammaF12, // п. 8.2.7, абзац 3: γf = 1,2
			Note: "дом и многоквартирный дом отнесены к «жилым зданиям» — " +
				"прямое попадание в п. 8.2.6 а). Если лестница ведёт на " +
				"обслуживаемую площадку, действует п. 8.2.6 г) — 0,3 кН/м.",
		}
	case engineering.PurposePublic, engineering.PurposeIndustrial:
		return RailingLoad{
			NormativeKNPerM: 0.8,
			Doc:             loadDocSP20,
			Clause:          loadClause826 + " в)",
			Basis:           "другие здания и помещения",
			GammaF:          gammaF12, // п. 8.2.7, абзац 3: γf = 1,2
			Note: "общественное и производственное здания отнесены к «другим " +
				"зданиям и помещениям» — это РЕШЕНИЕ проекта, в норме классов " +
				"«общественное»/«производственное» нет. НЕ ПРИМЕНИМО: " +
				"п. 8.2.6 б) трибуны и спортивные залы — 1,5 кН/м; " +
				"п. 8.2.6 г) обслуживающие площадки, мостики, ограждения крыш — " +
				"0,3 кН/м. Для лестницы в спортзале или на обслуживаемой " +
				"площадке нужно отдельное назначение.",
		}
	}
	// Неизвестное назначение — дом: тот же дефолт, что и в ProfileFor
	// (решение владельца 2026-10-13), иначе пустой заказ получал бы
	// нагрузку другого класса здания.
	return RailingLoadFor(engineering.PurposeHouse)
}

// StepLoad — равномерно распределённая кратковременная нагрузка на
// лестничный марш и площадку (табл. 8.3 СП 20, поз. 12).
//
// Таблица 8.3 перечисляет ПОМЕЩЕНИЯ, а не конструкции: «лестницы» в
// табл. не отдельной строкой, а упомянуты в поз. 12 вместе с вестибюлями,
// фойе и коридорами. Это важно для честности: нагрузка на лестницу взята
// не «в общем случае», а через то, к каким помещениям марш примыкает, —
// то есть поз. 12 задаёт её по позициям 1…7 и 11…13. Отсюда и 3,0, и 4,0,
// и 5,0 кПа: это разные помещения, а не разные лестницы.
type StepLoad struct {
	// NormativeKPa — нормативное значение, кПа.
	NormativeKPa float64
	// Doc и Clause — откуда взято.
	Doc    string
	Clause string
	// GammaF — п. 8.2.7, абзац 2: 1,3 при нормативном значении менее
	// 2,0 кПа, 1,2 при 2,0 кПа и более. Значение зависит от самой
	// нагрузки, поэтому вычисляется, а не зашито.
	GammaF float64
	// Basis — какие позиции табл. 8.3 дают это значение.
	Basis string
	// Note — оговорки.
	Note string
}

// Known — значение применимо.
func (l StepLoad) Known() bool { return l.NormativeKPa > 0 }

// DesignKPa — расчётное значение по п. 4.2: нормативное × γf.
func (l StepLoad) DesignKPa() float64 {
	if !l.Known() || l.GammaF <= 0 {
		return 0
	}
	return l.NormativeKPa * l.GammaF
}

// gammaFDistributed — γf для равномерно распределённых нагрузок по
// п. 8.2.7, абзац 2: 1,3 при нормативном значении менее 2,0 кПа,
// 1,2 при 2,0 кПа и более.
//
// Порог 2,0 кПа — из нормы, и он действует для равномерно нагрузок.
// НЕ применять его к сосредоточенным (там своя величина, п. 8.3.5) и не
// путать с γf от веса конструкций (табл. 7.1).
func gammaFDistributed(normativeKPa float64) float64 {
	switch {
	case normativeKPa <= 0:
		return 0
	case normativeKPa < 2.0:
		return 1.3
	default:
		return 1.2
	}
}

// StepLoadFor — равномерная нагрузка на лестничный марш по назначению.
//
// Соответствие назначений позициям табл. 8.3 — РЕШЕНИЕ проекта, а не
// цитата: норма оперирует помещениями, проект — назначениями здания.
// Как и в RailingLoadFor, несоответствия названы явно.
func StepLoadFor(p engineering.BuildingPurpose) StepLoad {
	switch p.PurposeEffective() {
	case engineering.PurposeHouse, engineering.PurposeFlat:
		// поз. 12 а) — «примыкающие к помещениям, указанным в позициях
		// 1, 2 и 3». Квартира жилого дома — поз. 1.
		return newStepLoad(3.0, "поз. 12 а)", "примыкание к помещениям 1, 2, 3; "+
			"квартира жилого здания — поз. 1 (1,5 кПа)",
			"дом и многоквартирный дом отнесены к помещениям поз. 1")
	case engineering.PurposePublic, engineering.PurposeIndustrial:
		// поз. 12 б) — «примыкающие к помещениям, указанным в позициях
		// 4, 5, 6, 11 и 13». Для производственных помещений релевантна
		// поз. 11 «участки обслуживания и ремонта оборудования в
		// производственных помещениях».
		return newStepLoad(4.0, "поз. 12 б)", "примыкание к помещениям 4, 5, 6, 11, 13; "+
			"для производственных — поз. 11 «участки обслуживания и ремонта "+
			"оборудования»",
			"общественное и производственное здания отнесены к поз. 12 б) — "+
				"это РЕШЕНИЕ проекта. НЕ ПРИМЕНИМО: поз. 12 в) — примыкание к "+
				"трибунам, 5,0 кПа; подсобные помещения могут давать 3,0 кПа по "+
				"поз. 12 а)")
	}
	return StepLoadFor(engineering.PurposeHouse)
}

func newStepLoad(kpa float64, clause, basis, note string) StepLoad {
	return StepLoad{
		NormativeKPa: kpa,
		Doc:          loadDocSP20,
		Clause:       "табл. 8.3, " + clause,
		GammaF:       gammaFDistributed(kpa),
		Basis:        basis,
		Note:         note,
	}
}

// ConcentratedLoad — сосредоточенная вертикальная нагрузка (п. 8.3).
//
// П. 8.3.1 требует проверять лестницы и перекрытия на сосредоточенную
// вертикальную нагрузку, приложенную в НЕБЛАГОПРИЯТНОМ положении на
// квадратной площадке со сторонами не более 10 см. Площадка — часть
// нормы, а не деталь реализации: нагрузка действует на пятно 100×100 мм,
// и «распределить её по всей ступени» — значит снять с неё всё, ради чего
// проверка и заведена.
type ConcentratedLoad struct {
	// NormativeKN — нормативное значение, кН.
	NormativeKN float64
	// PatchSideMM — сторона площадки, на которую действует нагрузка.
	PatchSideMM float64
	Doc         string
	Clause      string
	// GammaF — п. 8.3.5: γf = 1,2.
	GammaF float64
	Basis  string
	Note   string
}

// Known — значение применимо.
func (l ConcentratedLoad) Known() bool { return l.NormativeKN > 0 }

// DesignKN — расчётное значение по п. 4.2: нормативное × γf.
func (l ConcentratedLoad) DesignKN() float64 {
	if !l.Known() || l.GammaF <= 0 {
		return 0
	}
	return l.NormativeKN * l.GammaF
}

// StepConcentratedLoad — сосредоточенная нагрузка на лестничный марш и
// площадку: п. 8.3.4 а) «для перекрытий и лестниц — 1,5 кН».
//
// Террасы и балконы дали бы 1,0 кН (п. 8.3.4 б), и разница почти в
// полтора раза. Площадка лестницы — это лестница, а не терраса и не
// балкон, поэтому берётся именно 1,5 кН; отмечается, потому что
// «площадка» в проекте означает и отметку, и балкон в других местах.
func StepConcentratedLoad() ConcentratedLoad {
	return ConcentratedLoad{
		NormativeKN: 1.5,
		PatchSideMM: 100, // п. 8.3.1: не более 10 см
		Doc:         loadDocSP20,
		Clause:      "п. 8.3.4 а), площадка — п. 8.3.1",
		GammaF:      gammaF12, // п. 8.3.5: γf = 1,2
		Basis:       "для перекрытий и лестниц",
		Note: "НЕ ПРИМЕНИМО: п. 8.3.4 б) чердачные перекрытия, покрытия, " +
			"террасы и балконы — 1,0 кН; п. 8.3.4 в) покрытия, проходимые " +
			"только по трапам и мостикам, — 0,5 кН. Площадка лестницы " +
			"отнесена к лестницам; если она фактически терраса или балкон, " +
			"значение другое.",
	}
}

// SelfWeightFactor — γf для веса собственной конструкции (табл. 7.1).
//
// По п. 5.3 а) вес частей сооружений, в том числе несущих и ограждающих
// конструкций, — ПОСТОЯННАЯ нагрузка. Коэффициент даётся по материалу:
// металлические конструкции 1,05; бетонные (ρ>1600), железобетонные,
// каменные, армокаменные и деревянные — 1,1.
//
// Ноль означает «материал в таблице не найден», и это честнее, чем
// отдать металлу деревянные 1,1 или наоборот: разница в 5 % к постоянной
// нагрузке меняет итоговое сочетание.
func SelfWeightFactor(category string) float64 {
	switch category {
	case "Steel":
		return 1.05 // табл. 7.1, «Металлические, кроме случаев 7.3»
	case "Wood":
		return 1.1 // табл. 7.1, «…каменные, армокаменные, деревянные»
	}
	return 0
}

// CombinationShortTerm — коэффициенты сочетаний кратковременных нагрузок
// (п. 6.4 СП 20).
//
// Основное сочетание: ψt1 = 1,0 (нагрузка, соответствующая основной по
// степени влияния), ψt2 = 0,9, ψt3 = 0,8, ψt4 = 0,7. По п. 6.6 за одну
// временную нагрузку принимается нагрузка одного вида от одного
// источника — значит «люди» и «снег» считаются РАЗНЫМИ кратковременными
// и получают разные ψ, а не объединяются в одну.
//
// Индексация — с единицы, как в норме: ψt(1) — основная по степени
// влияния. Нулевой индекс означает «кратковременных нагрузок нет».
func CombinationShortTerm(index int) float64 {
	switch index {
	case 1:
		return 1.0
	case 2:
		return 0.9
	case 3:
		return 0.8
	case 4:
		return 0.7
	}
	return 0
}
