package geometry

// Качество тесселяции (S-165).
//
// Проблема, которую это решает. Владелец решил: геометрия у витрины и
// админки должна быть ОДНА, расходиться может только плотность треугольников.
// Проверено измерением, что так сделать «просто нельзя»:
//
//	одна проступь, R = 10, меняется только число сегментов дуги
//	 4 сегмента → объём 4 461 783 мм³
//	10 сегментов → объём 4 489 322 мм³  (+0,62 %)
//	64 сегмента  → объём 4 494 505 мм³  (+0,73 %)
//
// Плотность меняет объём, а объём идёт в расчёт стоимости. Если бы витрина
// и админка считали при разной плотности, одна и та же лестница стоила бы
// по-разному в зависимости от маршрута — ровно тот класс ошибок, который
// в проекте уже случался дважды (со ставками и с таблицей норматива).
//
// Причина зашита глубже: в B-Rep НЕТ аналитических кривых. Дуга — уже
// многоугольник в топологии, поэтому «плотность» и есть геометрия, и
// разделить их в одном теле невозможно.
//
// Решение: строить модель ДВАЖДЫ. Первый раз — производственная плотность,
// из неё берутся объём, площадь, раскрой и цена. Второй раз — грубая
// плотность, из неё берётся ТОЛЬКО меш для отображения. Цена от второй
// сборки не берётся никогда, поэтому расхождения цен не возникает по
// построению, а не по проверке.

// Quality — множитель допусков тесселяции.
type Quality struct {
	// ArcTolScale — во сколько раз увеличиваются допуски дуг. Больше
	// значение → меньше сегментов → легче меш и грубее видимая кромка.
	ArcTolScale float64
}

var (
	// ProductionQuality — точность, по которой считают объём, площадь,
	// раскрой и цену. Это то, что уходит в BOM и в смету.
	ProductionQuality = Quality{ArcTolScale: 1}

	// DisplayQuality — облегчённая точность ТОЛЬКО для показа. Числа,
	// посчитанные по ней, в расчёт не идут.
	DisplayQuality = Quality{ArcTolScale: 4}
)

// arcTol переводит производственный допуск в допуск данного качества.
// Нулевое или отрицательное значение Quality трактуется как производственное,
// чтобы пустой Quality никогда не ухудшал расчёт молча.
func (q Quality) arcTol(production float64) float64 {
	if q.ArcTolScale <= 0 {
		return production
	}
	return production * q.ArcTolScale
}

// relTol — то же для относительных допусков.
func (q Quality) relTol(production float64) float64 {
	return q.arcTol(production)
}
