-- 000050_material_code_c245 — переименование кода материала STEEL-S235 → STEEL-C245.
--
-- Зачем: S235 — класс-наследие ГОСТ 27772-89, снятый с производства ГОСТ
-- 27772-2015. В СП 16.13330.2017 табл. В.3 S235 остаётся только для листа
-- 2–4 мм, а каталог MFG-0005 выпускает лист 3–12 мм, то есть половина
-- допустимого диапазона попадала в класс, для которого таблица В.3 не даёт
-- значений. C245 действует для 2–20 мм и покрывает диапазон целиком.
--
-- Это изменение идентичности материала, а не переименование: код попадает в
-- персистентные данные, в публичный API /api/v1/public/materials и в путь
-- свача assets/pbr/<code>/, поэтому одной правки каталога мало.
--
-- TEXT-колонки хранят код каталога (MFG-0005) как строку без внешнего ключа,
-- так как справочник встроен в бинарь (DefaultMaterialRegistry) и не мигрируется
-- схемой. Значит заменять значения нужно здесь, данными.
--
-- stair_configurations.material_code — материал каркаса, NULL = автоназначение
-- по толщине; tread_material_code — материал ступени отдельно (миграция
-- 000034). store_rates.material_code — ставка магазина, NOT NULL: без
-- переименения прайс для C245 не найдётся и цена молча уедет на встроенную
-- заглушку (см. publicStoreRates).
UPDATE stair_configurations
    SET material_code = 'STEEL-C245'
    WHERE material_code = 'STEEL-S235';

UPDATE stair_configurations
    SET tread_material_code = 'STEEL-C245'
    WHERE tread_material_code = 'STEEL-S235';

UPDATE store_rates
    SET material_code = 'STEEL-C245'
    WHERE material_code = 'STEEL-S235';

-- Комментарий колонки из 000030 остался с примером старого кода. Историческую
-- миграцию не правим (она описывает состояние схемы на момент применения),
-- обновляем только комментарий в живой базе.
COMMENT ON COLUMN stair_configurations.material_code IS
    'Код материала каталога MFG-0005 (напр. STEEL-C245). NULL = автоназначение по толщине';