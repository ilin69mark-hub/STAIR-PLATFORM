-- 000049_config_purpose — назначение здания для нормативного профиля (S-236).
--
-- Зачем: нормы на лестницы разные для жилых, общественных и производственных
-- зданий, а заказ хранился без назначения — и проверялся одним набором
-- правил для всех (см. профили constraint.ProfileFor).
--
-- Значения: '' (NULL) | house | flat | public | industrial. Пусто = дом
-- (СП 55) — решение владельца 2026-10-13, дефолт заказов без назначения.
--
-- TEXT, а не ENUM: справочник назначений маленький, но он принадлежит
-- проекту, а не схеме, и добавление значения не должно требовать миграции
-- типа (как с ExtraFasteners — списком, не отдельными колонками).
ALTER TABLE stair_configurations
    ADD COLUMN purpose TEXT;