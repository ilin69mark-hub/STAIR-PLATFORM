-- Откат 000042: пересоздаёт ПУСТУЮ резервную структуру.
--
-- Строки к этому моменту уже в журнале (см. up) и обратно не переносятся:
-- down возвращает только оболочку, чтобы down/up цикл оставался
-- симметричным, а повторный up снова был no-op на пустом резерве.
-- Данные при откате не теряются: журнал не трогается.

CREATE TABLE IF NOT EXISTS audit_events_action_restore_backup (
    LIKE audit_events INCLUDING ALL
);
