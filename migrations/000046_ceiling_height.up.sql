-- 000046_ceiling_height — отметка низа перекрытия для расчёта просвета (S-168).
--
-- Зачем: поле «Просвет» (clearance_mm) — число, введённое пользователем, и
-- геометрией оно не использовалось: 2000 и 3000 давали побайтово одинаковую
-- модель. Теперь просвет считается по геометрии — от верха проступи до низа
-- перекрытия, худшая ступень та, что последней остаётся под перекрытием.
--
-- Для этого нужен факт из проёма: абсолютная отметка низа перекрытия в той же
-- системе координат, что и высота этажа (пол первого этажа — Z = 0).
-- Ноль означает «перекрытие не задано», и проверка просвета не выполняется —
-- как и room_fit, который не проверяется при нулевых габаритах помещения.
ALTER TABLE stair_configurations
    ADD COLUMN ceiling_height_mm DOUBLE PRECISION NOT NULL DEFAULT 0;